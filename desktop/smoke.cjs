const { app, session, BrowserWindow, screen } = require('electron');
const assert = require('node:assert/strict');
const { configure, createWindow } = require('./runtime.cjs');

app.setPath('userData', process.env.TIANJI_SMOKE_DATA);
app.on('window-all-closed', () => {});
const timeout = setTimeout(() => { console.error('Desktop smoke test timed out'); app.exit(1); }, 30000);
app.whenReady().then(async () => {
  await configure();
  console.log('Desktop smoke: configured');
  let win = await createWindow(false);
  const bounds = win.getBounds(), area = screen.getDisplayMatching(bounds).workArea;
  assert.ok(bounds.x >= area.x && bounds.y >= area.y);
  assert.ok(bounds.x + bounds.width <= area.x + area.width);
  assert.ok(bounds.y + bounds.height <= area.y + area.height);
  console.log('Desktop smoke: first page loaded');
  const preferences = win.webContents.getLastWebPreferences();
  assert.equal(preferences.nodeIntegration, false);
  assert.equal(preferences.contextIsolation, true);
  assert.equal(preferences.sandbox, true);
  assert.equal(await win.webContents.executeJavaScript(`new Promise(resolve => navigator.geolocation.getCurrentPosition(() => resolve(0), error => resolve(error.code)))`), 1);
  assert.equal(await win.webContents.executeJavaScript(`typeof require`), 'undefined');
  assert.equal(await win.webContents.executeJavaScript(`document.querySelector('#app').children.length > 0`), true);
  assert.equal(await win.webContents.executeJavaScript(`document.documentElement.classList.contains('wide-layout')`), true);
  await win.webContents.executeJavaScript(`localStorage.setItem('desktop-smoke', 'retained')`);
  win.destroy();
  win = await createWindow(false);
  console.log('Desktop smoke: second page loaded');
  assert.equal(await win.webContents.executeJavaScript(`localStorage.getItem('desktop-smoke')`), 'retained');
  assert.equal(await win.webContents.executeJavaScript(`fetch('app://tianji/package.json').then(r => r.status)`), 404);
  assert.equal(await win.webContents.executeJavaScript(`window.open('https://example.com') === null`), true);
  assert.equal(BrowserWindow.getAllWindows().length, 1);
  assert.equal(await win.webContents.executeJavaScript(`fetch('THIRD_PARTY_NOTICES.txt').then(r => r.text()).then(t => t.includes('Electron') && t.includes('lunar-javascript'))`), true);
  const licenseWindow = new Promise(resolve => app.once('browser-window-created', (_event, child) => resolve(child)));
  await win.webContents.executeJavaScript(`document.querySelector('a[href="THIRD_PARTY_NOTICES.txt"]').click()`);
  const child = await licenseWindow;
  await new Promise(resolve => child.webContents.once('did-finish-load', resolve));
  assert.equal(child.webContents.getURL(), 'app://tianji/THIRD_PARTY_NOTICES.txt');
  child.destroy();
  await session.defaultSession.flushStorageData();
  console.log('Desktop runtime smoke passed: offline render, sandbox, permissions, popup denial, local storage, notices');
  clearTimeout(timeout);
  win.destroy();
  app.quit();
}).catch(error => { console.error(error); app.exit(1); });
